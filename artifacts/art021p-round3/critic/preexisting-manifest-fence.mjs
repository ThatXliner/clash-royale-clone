import assert from 'node:assert/strict';
import { createVisualAssetManifest as createBaseline } from './pre-buried-coil-manifest.mjs';
import { createVisualAssetManifest as createCandidate } from '../../../src/content/visual-asset-manifest.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const here=path.dirname(fileURLToPath(import.meta.url));
const before=createBaseline().assets;
const after=createCandidate().assets;
const byId=new Map(after.map((asset)=>[asset.id,asset]));
const unchanged=before.filter((asset)=>JSON.stringify(asset)===JSON.stringify(byId.get(asset.id)));
const missing=before.filter((asset)=>!byId.has(asset.id)).map((asset)=>asset.id);
const changed=before.filter((asset)=>byId.has(asset.id)&&JSON.stringify(asset)!==JSON.stringify(byId.get(asset.id))).map((asset)=>asset.id);
const result={baseline:'bb0882312fa5d6edb83229ff66d9fd0c212d8068',baselineCount:before.length,candidateCount:after.length,unchangedPreexistingCount:unchanged.length,missing,changed};
assert.equal(before.length,24);
assert.equal(after.length,27);
assert.equal(unchanged.length,24);
assert.deepEqual(missing,[]);
assert.deepEqual(changed,[]);
writeFileSync(path.join(here,'preexisting-manifest-fence.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
